/** 构建 码位 → 目标字符串 查找表（模块加载时执行一次） */
const CJK_COMPAT_MAP: Map<number, string> = (() => {
  const map = new Map<number, string>();
  const decode = (t: string) =>
    t.split('+').map((h) => String.fromCharCode(parseInt(h, 16))).join('');
  for (const [key, vals] of CJK_COMPAT_SEGMENTS) {
    const targets = vals.split(',');
    if (typeof key === 'number') {
      map.set(key, decode(targets[0]));
      continue;
    }
    const [a, b] = key.split('-');
    const start = parseInt(a, 16);
    const end = parseInt(b, 16);
    for (let cp = start; cp <= end && cp - start < targets.length; cp++) {
      map.set(cp, decode(targets[cp - start]));
    }
  }
  return map;
})();

/**
 * 把 PDF 里常见的兼容码位还原为标准汉字。
 * 表里没有的码位原样返回，因此对正常文本零副作用。
 */
export function normalizeCjkCompat(text: string): string {
  if (!text) return text;
  let out = '';
  for (const ch of text) {
    const mapped = CJK_COMPAT_MAP.get(ch.codePointAt(0) as number);
    out += mapped === undefined ? ch : mapped;
  }
  return out;
}
